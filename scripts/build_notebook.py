from __future__ import annotations

from pathlib import Path

import nbformat as nbf

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "notebooks" / "01_exploratory_analysis.ipynb"

cells: list = []
md = lambda s: cells.append(nbf.v4.new_markdown_cell(s.strip()))  # noqa: E731
code = lambda s: cells.append(nbf.v4.new_code_cell(s.strip()))  # noqa: E731

md("""
# HeartSense: exploratory data analysis

UCI Heart Disease, Cleveland subset (303 patients, 13 clinical measurements, binary outcome).
This notebook is generated by `scripts/build_notebook.py` and uses the same functions as
`python -m heartsense.explore`, so the figures here are exactly the ones in `reports/figures/eda/`.
""")
code("""
import sys, json
from pathlib import Path
sys.path.insert(0, str(Path.cwd().parent / "src") if Path.cwd().name == "notebooks" else "src")
import pandas as pd
from IPython.display import Image, display
from heartsense import settings as cfg
from heartsense.ingest import load_clean, summary
from heartsense import explore

pd.set_option("display.width", 140)
df = load_clean()
summary(df)
""")
md(
    "## 1. Schema and a first look\nDescriptive names replace the UCI abbreviations; `target` = 1 when the original `num` diagnosis is > 0."
)
code("df.head(8)")
code("df.describe().T.round(2)")
md(
    "## 2. Missing values\nOnly `major_vessels` (4) and `thalassemia` (2) have gaps, originally encoded as `?`. They are kept as NaN and imputed *inside* the model pipeline."
)
code("df.isna().sum()[lambda s: s > 0]")
md(
    "## 3. Class balance\nThe outcome is close to balanced (46 % positive), so accuracy is meaningful but we still track ROC-AUC, recall and precision."
)
code("""
fig_dir = cfg.FIGURES_DIR / "eda"
display(Image(explore.fig_class_balance(df, fig_dir)))
""")
md(
    "## 4. Continuous features by outcome\nPatients with disease are older, reach a lower maximum heart rate and show larger exercise-induced ST depression."
)
code("display(Image(explore.fig_continuous_distributions(df, fig_dir)))")
md(
    "## 5. Disease prevalence by category\nAsymptomatic chest pain (type 4), a reversible thallium defect (7), exercise angina, a flat ST slope and more coloured vessels all raise the disease rate well above the overall 46 %."
)
code("display(Image(explore.fig_categorical_prevalence(df, fig_dir)))")
md(
    "## 6. Correlation structure\nSpearman correlation is used because several variables are ordinal. The strongest monotone relations with the target are `thalassemia`, `major_vessels`, `chest_pain_type`, `exercise_angina`, `max_heart_rate` and `st_depression`. Feature-feature correlations are moderate (|rho| < 0.6), so multicollinearity is not a concern for logistic regression."
)
code("display(Image(explore.fig_correlation(df, fig_dir)))")
code("""
corr = df.astype(float).corr(method="spearman")[cfg.TARGET].drop(cfg.TARGET)
corr.abs().sort_values(ascending=False).round(3).to_frame("|spearman rho| with target")
""")
md(
    "## 7. Chronotropic response\nMaximum heart rate falls with age (dashed line = 220 - age). Diseased patients cluster *below* the healthy cloud at the same age, which motivates the engineered feature `hr_reserve_pct = max_heart_rate / (220 - age)`."
)
code("display(Image(explore.fig_age_hr_scatter(df, fig_dir)))")
md(
    "## 8. ST depression and slope\nA depressed ST segment together with a flat or downsloping slope is the classic ischaemia pattern; this motivates `st_burden = st_depression x slope_weight`."
)
code("display(Image(explore.fig_st_depression_box(df, fig_dir)))")
md("""
## 9. Take-aways for modelling

* Small (303 rows), clean, near-balanced tabular dataset: regularised linear models and small ensembles are appropriate; cross-validation must be repeated to get stable estimates.
* Six missing cells only: median / most-frequent imputation inside the pipeline is sufficient.
* Nominal codes (`chest_pain_type`, `rest_ecg`, `st_slope`, `thalassemia`) are one-hot encoded; continuous features are standardised; three engineered features add clinical prior knowledge.
* Strongest univariate signals: thallium result, number of vessels, chest-pain type, exercise angina, max heart rate, ST depression.
""")
code("json.dumps(explore.profile(df)['top_correlates_with_target'], indent=2)")

nb = nbf.v4.new_notebook(
    cells=cells,
    metadata={
        "kernelspec": {"name": "python3", "display_name": "Python 3", "language": "python"},
        "language_info": {"name": "python"},
    },
)
OUT.parent.mkdir(exist_ok=True)
nbf.write(nb, OUT)
print(f"wrote {OUT.relative_to(ROOT)} ({len(cells)} cells)")
